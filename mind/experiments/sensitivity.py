"""One-at-a-time sensitivity of the headline claims. Protocol: docs/protocols/2e_sensitivity.md.

    python -m mind.experiments.sensitivity

Writes mind/results/sensitivity.json and docs/results/SENSITIVITY.md. ETA is never varied.
Each value runs in a fresh worker that overrides the constant where the mind reads it.
"""

import json
import math
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import contracts  # noqa: F401  (must load before mind; see conftest.py)
import mind.belief as belief
import mind.config as config
import mind.decoherence as decoherence
import mind.quantum_mind as quantum_mind
from engine.events import VOLCANIC
from engine.simulation import SimulationEngine
from mind.experiments.validate import evacuation_delay
from mind.model import bloch_vector, p_protect_closed_form

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "mind" / "results" / "sensitivity.json"
TABLE = ROOT / "docs" / "results" / "SENSITIVITY.md"
SEEDS = range(100)
DEFAULTS = dict(CF_SAFE_SAFETY=0.95, CF_DANGER_SAFETY=0.05, STRESS_FLOOR=0.2, STRESS_SPAN=0.7, angle_scale=1.0)
GRID = dict(
    CF_SAFE_SAFETY=(0.90, 0.95, 0.99),
    CF_DANGER_SAFETY=(0.01, 0.05, 0.10),
    STRESS_FLOOR=(0.1, 0.2, 0.3),
    STRESS_SPAN=(0.5, 0.7, 0.9),
    angle_scale=(0.8, 0.9, 1.0, 1.1, 1.2),
)
ROBUST_MIN_GAP_SHARE = 0.5
ROBUST_SURVIVAL_POINTS = 2.0


def apply_override(name, value):
    if name in ("CF_SAFE_SAFETY", "CF_DANGER_SAFETY"):
        setattr(quantum_mind, name, value)
    elif name in ("STRESS_FLOOR", "STRESS_SPAN"):
        setattr(decoherence, name, value)
    elif name == "angle_scale":
        belief.EVENT_GATES = {event: (axis, angle * value) for event, (axis, angle) in config.EVENT_GATES.items()}
    else:
        raise KeyError(name)


def paper_order_gap():
    """The paper's 0.140: (storm, tremor, gas_plume) minus (storm, gas_plume, tremor), lam=0, q fixed at 0.69 and 0.59."""

    def p_protect(events):
        x, _y, z = bloch_vector(belief.run_events(belief.prepare_belief(0.85), events, 0.0))
        return p_protect_closed_form((1 - z) / 2, x, 0.69, 0.59, config.ETA)

    return p_protect(["storm", "tremor", "gas_plume"]) - p_protect(["storm", "gas_plume", "tremor"])


def order_gap():
    """The same pair through the mind itself, with its own q values, so the counterfactual constants act."""
    from engine.agent import SurvivalAgent

    state = SurvivalAgent().get_state()
    forward = quantum_mind._decide(dict(state, recent_events=["storm", "tremor", "gas_plume"]), force_lam=0.0, suppress_order_gap=True)
    reverse = quantum_mind._decide(dict(state, recent_events=["storm", "gas_plume", "tremor"]), force_lam=0.0, suppress_order_gap=True)
    return forward["quantum"]["p_protect"] - reverse["quantum"]["p_protect"]


def one_value(job):
    name, value = job
    apply_override(name, value)
    quantum, mixture = [], []
    for seed in SEEDS:
        for store, mind_type in ((quantum, "quantum"), (mixture, "classical_mixture")):
            timeline = SimulationEngine(seed=seed, mind_type=mind_type).run()
            store.append((timeline["outcome"] == "survived", evacuation_delay(timeline["steps"], VOLCANIC)))
    diffs = [a[1] - b[1] for a, b in zip(quantum, mixture) if a[1] is not None and b[1] is not None]
    mean = sum(diffs) / len(diffs) if diffs else float("nan")
    se = math.sqrt(sum((d - mean) ** 2 for d in diffs) / (len(diffs) - 1) / len(diffs)) if len(diffs) > 1 else float("nan")
    return dict(
        constant=name,
        value=value,
        is_default=DEFAULTS[name] == value,
        paper_gap=paper_order_gap(),
        order_gap=order_gap(),
        delay=mean,
        delay_se=se,
        paired_n=len(diffs),
        survival_quantum=sum(q[0] for q in quantum) / len(quantum),
        survival_mixture=sum(m[0] for m in mixture) / len(mixture),
    )


def verdicts(rows):
    baseline = next(r for r in rows if r["is_default"])
    out = {}
    for name in GRID:
        group = [r for r in rows if r["constant"] == name]
        gap_ok = all(r["order_gap"] * baseline["order_gap"] > 0 and abs(r["order_gap"]) >= ROBUST_MIN_GAP_SHARE * abs(baseline["order_gap"]) for r in group)
        delay_ok = all(r["delay"] - 1.96 * r["delay_se"] > 0 for r in group)
        survival_ok = all(abs(r["survival_quantum"] - r["survival_mixture"]) * 100 <= ROBUST_SURVIVAL_POINTS for r in group)
        out[name] = dict(order_gap=gap_ok, delay=delay_ok, survival=survival_ok)
    return out


def render(rows, verdict):
    word = {True: "robust", False: "**sensitive**"}
    lines = [
        "# Sensitivity",
        "",
        "_Generated by `python -m mind.experiments.sensitivity`. Do not edit by hand. Protocol: [2e_sensitivity.md](../protocols/2e_sensitivity.md)._",
        "",
        "One constant varies at a time, volcano seeds 0 to 99, default rule. `ETA` is fixed. Model output, not predictions.",
        "",
        "`Paper gap` holds q at 0.69 and 0.59, as the paper's 0.140 does. `Mind gap` is the same pair through the mind with its own q values, which is where the counterfactual constants act.",
        "",
        "| Constant | Value | Paper gap | Mind gap | Delay, quantum minus mixture (steps) | Quantum survival | Mixture survival |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        mark = " (default)" if r["is_default"] else ""
        lines.append(
            f"| `{r['constant']}` | {r['value']}{mark} | {r['paper_gap']:+.3f} | {r['order_gap']:+.3f} | {r['delay']:+.2f} ± {1.96 * r['delay_se']:.2f} | "
            f"{r['survival_quantum'] * 100:.1f}% | {r['survival_mixture'] * 100:.1f}% |"
        )
    lines += [
        "",
        "## How robust are the claims",
        "",
        "The paper is not in this repository, so this mapping of labels to claims is an assumption: "
        "**C2** the order effect, **C3** a positive evacuation delay, **C4** no survival change on the default volcano. "
        "**C1**, the calibration to Tversky & Shafir, is a fit through `ETA`, which is held fixed here, so it does not vary. "
        "The robustness rules were fixed in the protocol.",
        "",
        "| Constant | C2 order gap | C3 delay above 0 | C4 survival within 2 points |",
        "| --- | --- | --- | --- |",
    ]
    for name, v in verdict.items():
        lines.append(f"| `{name}` | {word[v['order_gap']]} | {word[v['delay']]} | {word[v['survival']]} |")
    return "\n".join(lines) + "\n"


def main():
    jobs = [(name, value) for name, values in GRID.items() for value in values]
    with ProcessPoolExecutor(max_tasks_per_child=1) as pool:
        rows = list(pool.map(one_value, jobs))
    verdict = verdicts(rows)
    OUT.write_text(json.dumps(dict(rows=rows, verdicts=verdict), indent=1), encoding="utf-8")
    TABLE.write_text(render(rows, verdict), encoding="utf-8")
    print(render(rows, verdict))


if __name__ == "__main__":
    main()
