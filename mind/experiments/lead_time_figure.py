"""Draws the survival and delay curves from mind/results/lead_time/curves.csv, and writes the table.

    python -m mind.experiments.lead_time_figure

Figure: docs/images/lead_time_sweep.png. Table: docs/results/LEAD_TIME.md. The CSVs are the data view.
"""

import csv
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "mind" / "results" / "lead_time"
FIGURE = ROOT / "docs" / "images" / "lead_time_sweep.png"
TABLE = ROOT / "docs" / "results" / "LEAD_TIME.md"
SURFACE, INK, SECONDARY, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e6e5e0"
ARMS = (
    ("quantum", "Quantum", "#2a78d6", "-"),
    ("classical_mixture", "Mixture control", "#eb6834", "-"),
    ("classical_no_interference", "No interference", "#1baf7a", "--"),
    ("markov_hesitation", "Markov, h fitted", "#eda100", "--"),
    ("markov_hesitation_ts", "Markov, h from T&S", "#e87ba4", "-."),
)
LABEL = {key: name for key, name, _, _ in ARMS}


def read(name):
    with (DATA / name).open(encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream))


def draw(curves):
    rows = [r for r in curves if r["distance_tiles"] == "all"]
    figure, axes = plt.subplots(1, 2, figsize=(11, 4.4), dpi=160, facecolor=SURFACE)
    panels = ((axes[0], "survived", "Survived to the end of the run", 100, "%"), (axes[1], "delay_steps", "Steps from first sign to first hide", 1, ""))
    for axis, metric, title, factor, unit in panels:
        axis.set_facecolor(SURFACE)
        for key, name, color, style in ARMS:
            arm = sorted((r for r in rows if r["arm"] == key), key=lambda r: float(r["lead_hours"]))
            x = [float(r["lead_hours"]) for r in arm]
            y = [float(r[metric]) * factor for r in arm]
            low = [float(r[metric + "_low"]) * factor for r in arm]
            high = [float(r[metric + "_high"]) * factor for r in arm]
            axis.fill_between(x, low, high, color=color, alpha=0.12, linewidth=0)
            axis.plot(x, y, color=color, linestyle=style, linewidth=2, marker="o", markersize=4, label=name)
        axis.set_title(title, loc="left", color=INK, fontsize=12)
        axis.set_xlabel("Warning lead, hours (first sign to first flow)", color=SECONDARY, fontsize=10)
        axis.tick_params(colors=SECONDARY, labelsize=9, length=0)
        axis.grid(axis="y", color=GRID, linewidth=1)
        axis.set_axisbelow(True)
        for side in ("top", "right", "left"):
            axis.spines[side].set_visible(False)
        axis.spines["bottom"].set_color(GRID)
        if unit:
            axis.yaxis.set_major_formatter(lambda value, _pos: f"{value:.0f}%")
    handles, labels = axes[0].get_legend_handles_labels()
    figure.legend(handles, labels, loc="lower center", ncol=5, frameon=False, fontsize=9, labelcolor=INK)
    figure.text(0.01, 0.97, "Model output, not a prediction. Shaded bands: 95% bootstrap over seeds.", color=SECONDARY, fontsize=9, va="top")
    figure.tight_layout(rect=(0, 0.08, 1, 0.95))
    FIGURE.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(FIGURE, facecolor=SURFACE)
    plt.close(figure)


def render(curves, contrasts, meta):
    catalog = meta["catalog"]
    lines = [
        "# Lead-time sweep",
        "",
        "_Generated by `python -m mind.experiments.lead_time_figure`. Do not edit by hand. "
        "Protocols: [2a](../protocols/2a_lead_time_sweep.md), [2b](../protocols/2b_control_arms.md)._",
        "",
        f"{meta['seeds'][1] - meta['seeds'][0] + 1} seeds, {meta['replicates']} replicates, {len(meta['distances_tiles'])} distances, "
        f"{meta['runs']:,} runs. Catalogue leads: median {catalog['median']:.1f} h, quartiles {catalog['q25']:.1f} and {catalog['q75']:.1f} h, "
        f"90th percentile {catalog['q90']:.0f} h, n = {catalog['n']}. Model output, not a prediction.",
        "",
        "![Survival and delay against lead time](../images/lead_time_sweep.png)",
        "",
        "## Survival to the end of the run, all distances",
        "",
        "| Lead (h) | " + " | ".join(LABEL.values()) + " |",
        "| --- |" + " --- |" * len(LABEL),
    ]
    rows = [r for r in curves if r["distance_tiles"] == "all"]
    leads = sorted({float(r["lead_hours"]) for r in rows})

    def cell(arm, lead, metric, factor):
        row = next(r for r in rows if r["arm"] == arm and float(r["lead_hours"]) == lead)
        return f"{float(row[metric]) * factor:.1f}"

    for lead in leads:
        lines.append(f"| {lead:g} | " + " | ".join(cell(a, lead, "survived", 100) + "%" for a in LABEL) + " |")
    lines += ["", "## Delay, first sign to first hide (steps)", "", "| Lead (h) | " + " | ".join(LABEL.values()) + " |", "| --- |" + " --- |" * len(LABEL)]
    for lead in leads:
        lines.append(f"| {lead:g} | " + " | ".join(cell(a, lead, "delay_steps", 1) for a in LABEL) + " |")
    lines += [
        "",
        "## Paired differences, quantum minus each control",
        "",
        "Seed is the unit. p is Holm-adjusted across the 8 leads, within each control and metric. **Bold** means p < 0.05.",
        "",
        "| Control | Lead (h) | Survival difference (points) | 95% interval | p | Delay difference (steps) | 95% interval | p |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in contrasts:
        survival, delay = float(row["survived_p_holm"]), float(row["delay_steps_p_holm"])
        mark_s, mark_d = ("**" if survival < 0.05 else ""), ("**" if delay < 0.05 else "")
        lines.append(
            f"| {LABEL[row['control']]} | {float(row['lead_hours']):g} | {mark_s}{float(row['survived_diff']) * 100:+.1f}{mark_s} | "
            f"{float(row['survived_low']) * 100:+.1f} to {float(row['survived_high']) * 100:+.1f} | {survival:.3f} | "
            f"{mark_d}{float(row['delay_steps_diff']):+.2f}{mark_d} | {float(row['delay_steps_low']):+.2f} to {float(row['delay_steps_high']):+.2f} | {delay:.3f} |"
        )
    return "\n".join(lines) + "\n"


def main():
    curves, contrasts = read("curves.csv"), read("contrasts.csv")
    meta = json.loads((DATA / "meta.json").read_text(encoding="utf-8"))
    draw(curves)
    TABLE.write_text(render(curves, contrasts, meta), encoding="utf-8")
    print("wrote", FIGURE, TABLE)


if __name__ == "__main__":
    main()
