"""Every category, what it holds, and how complete it is. `python -m stranded_physics.catalog` rewrites CATALOG.md."""
from __future__ import annotations

import sys
import tomllib
from pathlib import Path

from stranded_physics.core.api import InterfaceError
from stranded_physics.core.records import load_datasets, load_parameters

DOMAINS = Path(__file__).resolve().parent / "domains"
OUTPUT = Path(__file__).resolve().parents[1] / "workboard" / "CATALOG.md"
CATEGORY_KEYS = {"id", "title", "status", "owner", "first_model", "owns", "must_not_own", "outputs", "wanted"}
STATUSES = {"model", "data_only"}


def load_category(path: Path) -> dict:
    entry = tomllib.loads((path / "category.toml").read_text(encoding="utf-8"))
    unknown = set(entry) - CATEGORY_KEYS
    if unknown:
        raise InterfaceError(f"{path}: unknown keys {sorted(unknown)}")
    if entry["id"] != path.name:
        raise InterfaceError(f"{path}: id {entry['id']!r} does not match the folder")
    if entry["status"] not in STATUSES:
        raise InterfaceError(f"{path}: status must be one of {sorted(STATUSES)}")
    return entry


def build() -> str:
    lines = ["# Data and model catalog", "", "Generated by `python -m stranded_physics.catalog`. Do not edit by hand.",
             "To add data: add a record to that category's `datasets.toml`, then rerun.", ""]
    categories = [load_category(p) for p in sorted(DOMAINS.iterdir()) if (p / "category.toml").exists()]
    lines += ["| Category | Status | Owner | Datasets | Parameters | First model |", "|---|---|---|---|---|---|"]
    details = []
    for entry in categories:
        folder = DOMAINS / entry["id"]
        datasets = load_datasets(folder / "datasets.toml", entry["id"])
        parameters = load_parameters(folder / "params.toml")
        lines.append(f"| {entry['id']} | {entry['status']} | {entry.get('owner') or 'unclaimed'} | {len(datasets)} | {len(parameters)} | {entry.get('first_model') or 'none yet'} |")
        details += ["", f"## {entry['id']}: {entry['title']}", "", f"**Owns:** {entry['owns']}", "", f"**Must not own:** {entry['must_not_own']}"]
        if datasets:
            details += ["", "| Dataset | Kind | Split | Licence confirmed | Notes |", "|---|---|---|---|---|"]
            details += [f"| {d.id} | {d.kind} | {d.split} | {'yes' if d.licence_confirmed else 'no'} | {d.notes} |" for d in datasets]
        if entry.get("wanted"):
            details += ["", "**Still wanted:**"] + [f"- {item}" for item in entry["wanted"]]
    return "\n".join(lines + details) + "\n"


def main() -> int:
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
