"""Looks after the public gallery in community/.

    python tools/publish_sim.py add my_sim.qsim   # check it, copy it in, and rebuild the list
    python tools/publish_sim.py check             # check every sim, and that the list is up to date
    python tools/publish_sim.py rebuild           # rebuild the list, after removing a sim

community/index.json is what the app reads. community/README.md is the page people see on GitHub.
A sim reaches the public when its file is merged to main, after the review in community/REVIEW.md.
`check` runs on every pull request.
"""

import argparse
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from stranded_physics.core.api import InterfaceError  # noqa: E402
from stranded_physics.entities import simfile  # noqa: E402

COMMUNITY = ROOT / "community"
SIMS = COMMUNITY / "sims"
INDEX = COMMUNITY / "index.json"
PAGE = COMMUNITY / "README.md"
INTRO = """# Community sims

_Generated by `tools/publish_sim.py`. Do not edit by hand._

Scenarios people have made in Qognition. Open one in the app from **Open > Community**, or download a `.qsim` file and drop it on the app's window.

**Anyone can publish, and nobody has validated these.** Each sim is [reviewed](REVIEW.md) to check it is safe and fair to publish, not that it is accurate. A sim is a model someone built, not a prediction of any real event, and it is not advice for any real emergency. A sim file holds data only, and the app checks it before opening it.

Each sim is shared by its author under [CC BY 4.0](LICENSE.txt). Credit the author named below if you reuse one. To ask for a sim to be removed, open an issue.

To add yours, choose **Share > Publish online** in the app's builder, or send a pull request adding your file to `community/sims/`.
"""


def rule_problems(path, sim):
    """What keeps a valid sim file out of the gallery."""
    problems = []
    if sim.draft.header["id"] != path.stem:
        problems.append(f"The file has to be named {sim.draft.header['id']}{simfile.SUFFIX}, after the sim's id")
    if not sim.description.strip():
        problems.append("It needs a description")
    if sim.licence != simfile.LICENCE:
        problems.append(f"It has to be licensed {simfile.LICENCE}. Export it again from the app")
    return problems


def closer_look(sims):
    """Sims a reviewer must treat with extra care. See community/REVIEW.md."""
    return [path.name for path, sim in sims if sim.draft.header["place"] == "real"]


def row_for(path, sim):
    return dict(
        file=path.name, title=sim.title, author=sim.author, description=sim.description, needs_data_pack=sim.needs_data_pack, seed=sim.seed, sha256=sim.sha256
    )


def load_all():
    return [(path, simfile.read_path(path)) for path in sorted(SIMS.glob(f"*{simfile.SUFFIX}"))]


def index_text(rows):
    return json.dumps(dict(format="qognition-gallery", version=1, sims=rows), indent=1, ensure_ascii=False) + "\n"


def _cell(text):
    return " ".join(str(text).replace("|", "/").replace("<", "(").replace(">", ")").split())


def page_text(rows):
    lines = [INTRO, "| Sim | Made by | What it is | Needs the data pack |", "| --- | --- | --- | --- |"]
    for row in rows:
        link = f"[{_cell(row['title']).replace('[', '(').replace(']', ')')}](sims/{row['file']})"
        lines.append(f"| {link} | {_cell(row['author']) or 'Anonymous'} | {_cell(row['description'])} | {'Yes' if row['needs_data_pack'] else 'No'} |")
    return "\n".join(lines) + "\n"


def rebuild():
    rows = [row_for(path, sim) for path, sim in load_all()]
    INDEX.write_text(index_text(rows), encoding="utf-8", newline="\n")
    PAGE.write_text(page_text(rows), encoding="utf-8", newline="\n")
    return rows


def add(source):
    source = Path(source)
    sim = simfile.read_path(source)
    problems = rule_problems(source, sim)
    if problems:
        raise InterfaceError("; ".join(problems))
    target = SIMS / source.name
    if target.exists() and target.read_bytes() != source.read_bytes():
        raise InterfaceError(f"{target.name} is already in the gallery with different contents. Give yours a new id")
    SIMS.mkdir(parents=True, exist_ok=True)
    if target.resolve() != source.resolve():
        shutil.copyfile(source, target)
    return rebuild()


def check():
    problems = []
    rows = []
    for path in sorted(SIMS.glob("*")):
        try:
            sim = simfile.read_path(path)
            problems += [f"{path.name}: {problem}" for problem in rule_problems(path, sim)]
            rows.append(row_for(path, sim))
        except InterfaceError as error:
            problems.append(f"{path.name}: {error}")
    if not problems:
        if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != index_text(rows):
            problems.append("community/index.json is out of date. Run: python tools/publish_sim.py add <file>")
        if not PAGE.exists() or PAGE.read_text(encoding="utf-8") != page_text(rows):
            problems.append("community/README.md is out of date. Run: python tools/publish_sim.py add <file>")
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("add").add_argument("file")
    commands.add_parser("check")
    commands.add_parser("rebuild")
    args = parser.parse_args()
    if args.command == "add":
        try:
            rows = add(args.file)
        except InterfaceError as error:
            print(f"Not added: {error}")
            return 1
        print(f"The gallery now lists {len(rows)} sims. Commit community/ and merge it to main to publish.")
        return 0
    if args.command == "rebuild":
        print(f"The gallery now lists {len(rebuild())} sims.")
        return 0
    problems = check()
    for problem in problems:
        print(problem)
    if not problems:
        for name in closer_look(load_all()):
            print(f"{name} is set in a real place. Review it with the extra checks in community/REVIEW.md.")
    print("Gallery check failed." if problems else "Gallery check passed.")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
